const fs=require('fs'),vm=require('vm'),path=require('path');
const root=process.argv[2]||'.';
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const pass=[],fail=[];const ok=(c,m)=>(c?pass:fail).push(m);
const scripts=[...html.matchAll(/<script(?:[^>]*)>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
for(let i=0;i<scripts.length;i++)try{new vm.Script(scripts[i]);pass.push(`script ${i+1} syntax`)}catch(e){fail.push(`script ${i+1} syntax: ${e.message}`)}
const move=(html.match(/function move\(dir\)\{[\s\S]*?\n\}/)||[''])[0];
const keyUse=(html.match(/function tryUseStoryKey\(item,index\)\{[\s\S]*?\n\}/)||[''])[0];
const renderInv=(html.match(/function renderInv\(\)\{[\s\S]*?\n\}/)||[''])[0];
ok(move.includes("if(c.keyItem){"),'keyed locked gate has dedicated locked-door branch');
ok(move.includes("toast('DØREN ER LÅST')"),'tapping keyed gate only reports that the door is locked');
ok(move.includes("addLog('FANT EN LÅST DØR.')"),'locked-door fiction does not reveal the key solution');
ok(!move.includes("state.inventory.splice(keyIndex,1)"),'door tap does not auto-consume story key');
ok(keyUse.includes("x.locked&&!x.unlocked&&x.keyItem===item"),'explicit key use requires adjacent matching locked gate');
ok(keyUse.includes("state.inventory.splice(index,1)"),'explicit successful key use removes key from inventory');
ok(keyUse.includes("c.unlocked=true")&&keyUse.includes("render();toast('NØKKELEN PASSER - DØREN ER ÅPEN!')"),'explicit key use opens but does not traverse gate');
ok(!keyUse.includes('state.currentRoomId='),'explicit key use never moves the hero through the door');
ok(renderInv.includes("isStoryKey=item===storyKey"),'inventory identifies current scenario key');
ok(renderInv.includes('VIKTIG · KAN IKKE FJERNES')&&renderInv.includes('data-use="${i}"'),'scenario key remains protected but has BRUK action');
ok(html.includes('KANSKJE DU HAR NOE I SEKKEN?'),'narrator has optional open hint without naming the solution');
ok(html.includes('<summary>FORTELLERHJELP</summary>'),'puzzle card exposes narrator help');
ok(html.includes('LA BARNET TENKE UTEN TERNING'),'puzzle explicitly says no die for the puzzle itself');
ok(html.includes('ET PUZZLE ER ET SPOR, IKKE ET AUTOMATISK FREMGANGSSTEG'),'puzzle narrator help does not invent generic progress');
ok(html.includes("toast('PUZZLET ER LØST')"),'puzzle solve gives explicit puzzle feedback');
const puzzleHandler=(html.split("$$('[data-epuzzle]')")[1]||'').split('\n')[0];
ok(!puzzleHandler.includes('ev.progress='),'puzzle solve does not mutate generic encounter progress');
console.log(JSON.stringify({ok:fail.length===0,passCount:pass.length,failCount:fail.length,fail},null,2));
if(fail.length)process.exit(1);
