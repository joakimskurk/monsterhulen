const fs=require('fs');
const path=require('path');
let pass=0,fail=0;
function ok(name,cond){if(cond){pass++;console.log('PASS',name)}else{fail++;console.error('FAIL',name)}}
const root=path.resolve(__dirname,'..');
const p=path.join(root,'visual','structural-map-v3-acceptance.json');
const c=JSON.parse(fs.readFileSync(p,'utf8'));
ok('logical source cell remains 32',c.source.logicalCellPx===32);
ok('runtime grid remains 13x13',c.source.mapGrid.width===13&&c.source.mapGrid.height===13);
ok('integer scaling only',c.source.integerScalingOnly===true);
ok('preferred display scale is 2x',c.presentation.preferredDisplayScale===2);
ok('preferred cell display is 64 CSS px',c.presentation.logicalCellCssPxAtPreferredScale===64);
ok('fit-all shrink below 2x forbidden',c.presentation.fitAllShrinkBelow2x===false);
ok('minimum viewport is at least 320x320',c.presentation.minMapViewportCssPx.width>=320&&c.presentation.minMapViewportCssPx.height>=320);
ok('occupancy target avoids tiny minimap',c.presentation.exploredBoundsViewportOccupancyTargetPct.min>=50&&c.presentation.exploredBoundsViewportOccupancyTargetPct.max<=90);
ok('floor canvas 32x32',c.floor.canvas.width===32&&c.floor.canvas.height===32);
ok('floor has 4px quiet edge zone',c.floor.quietEdgeZonePx===4);
ok('floor detail stays off perimeter',c.floor.detailRegion.xMin>=4&&c.floor.detailRegion.xMax<=27&&c.floor.detailRegion.yMin>=4&&c.floor.detailRegion.yMax<=27);
ok('floor semantic false',c.floor.semantic===false);
ok('floor edge frame forbidden',c.floor.edgeFrameForbidden===true);
ok('wall depth strengthened beyond V2',c.wall.targetDepthPx===8);
ok('same-room walls forbidden',c.wall.sameRoomJoinWallAllowed===false);
ok('wall hard structural alpha',c.wall.hardStructuralAlpha===true);
ok('connection remains 32x32 source',c.connection.canvas.width===32&&c.connection.canvas.height===32);
ok('connection anchored to shared boundary',c.connection.anchor==='shared-boundary-midpoint');
ok('V3 aperture is 18px',c.connection.aperturePx===18);
ok('detached lock forbidden',c.connection.detachedLockSignalAllowed===false);
ok('blocker belongs on threshold',c.connection.blockedSignalPlacement==='threshold');
ok('all nine synthetic proofs required',Array.isArray(c.syntheticRequired)&&c.syntheticRequired.length===9);
ok('five production gates required',Array.isArray(c.productionGates)&&c.productionGates.length===5);
ok('manual acceptance is substantive',Array.isArray(c.manualAcceptanceAllMustPass)&&c.manualAcceptanceAllMustPass.length>=12);
ok('room-first acceptance explicit',c.manualAcceptanceAllMustPass.includes('room_reads_before_grid'));
ok('mobile pan/focus acceptance explicit',c.manualAcceptanceAllMustPass.includes('mobile_uses_focus_pan_not_fit_all'));
console.log(`RESULT ${pass} PASS / ${fail} FAIL`);
if(fail)process.exit(1);
