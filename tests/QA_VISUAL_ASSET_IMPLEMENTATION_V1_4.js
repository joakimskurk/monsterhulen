const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const css=fs.readFileSync(path.join(root,'visual/runtime-assets-v1_4.css'),'utf8');
const js=fs.readFileSync(path.join(root,'visual/runtime-assets-v1_4.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'visual/asset-manifest-v1_4.json'),'utf8'));
let pass=0,fail=0;
function t(name,ok){if(ok){pass++;console.log('PASS',name)}else{fail++;console.log('FAIL',name)}}
t('31 split PNG assets',Object.keys(manifest.assets).length===31);
t('all manifest hashes present',Object.values(manifest.assets).every(x=>/^[a-f0-9]{64}$/.test(x.sha256)&&x.bytes>0));
t('no stretched button bitmaps',!css.includes('button_green.png')&&!css.includes('button_blue.png')&&!css.includes('button_orange.png')&&!css.includes('button_purple.png'));
t('no stretched panel bitmap',!css.includes('ui_panel_dark.png'));
t('CSS pixel button geometry present',css.includes('box-shadow:inset 0 0 0 2px #122131'));
t('room-level current state uses joined edges',css.includes('.tile.current:not(.joinN)')&&css.includes('.tile.current:not(.joinE)'));
t('per-cell outline disabled',css.includes('.tile.current{outline:none!important'));
t('focused map viewport present',css.includes('.v14MapViewport'));
t('mobile surface nav non-fixed',css.includes('.v14BottomNav{position:relative'));
t('mobile old tabs hidden',css.includes('.mobileTabs{display:none!important'));
t('generic scene returns null',js.includes('return null}'));
t('special scenes depend on visible room text only',js.includes('room?.name')&&js.includes('room?.desc')&&!js.includes('scenario'));
t('no gameplay move call introduced',!js.match(/\bmove\s*\(/));
t('no direct state mutation introduced',!js.match(/state\s*\.[A-Za-z0-9_]+\s*=/));
t('map centering reads CSS padding dynamically',js.includes('getComputedStyle(map)')&&js.includes('paddingLeft'));
t('mobile nav uses separated asset icons',js.includes('icon_map.png')&&js.includes('icon_search.png')&&js.includes('icon_bag.png')&&js.includes('icon_book.png'));
t('event markers mapped to sprites',js.includes('v14MapEventIcon')&&js.includes('icon_skull.png')&&js.includes('icon_exclaim.png'));
t('hero mappings use stable IDs',js.includes('CHAR_HERO_14')&&js.includes('CHAR_HERO_15')&&js.includes('CHAR_HERO_19'));
t('inventory is visual only',js.includes('itemAsset')&&!js.includes('consume'));
t('map copy is product-specific',js.includes('UTFORSK HULEN. ? VISER EN UKJENT VEI'));
console.log(`${pass} PASS / ${fail} FAIL`);process.exit(fail?1:0);
