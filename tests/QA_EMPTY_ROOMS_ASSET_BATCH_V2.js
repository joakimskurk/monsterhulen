const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'visual/tileset-manifest-v2.json'),'utf8'));
const hashes=JSON.parse(fs.readFileSync(path.join(root,'visual/empty-rooms-assets-v2.sha256.json'),'utf8'));
const generator=fs.readFileSync(path.join(root,'tools/generate_empty_rooms_v2.py'),'utf8');
let pass=0, fail=0;
function ok(cond,msg){ if(cond){pass++; console.log('PASS',msg);} else {fail++; console.error('FAIL',msg);} }
const assets=manifest.assets;
ok(manifest.tileSize===32,'tile size 32');
ok(manifest.mapGrid.width===13&&manifest.mapGrid.height===13,'map grid 13x13');
ok(manifest.atlas.width===512&&manifest.atlas.height===512&&manifest.atlas.cell===32,'atlas 512/32');
ok(assets.length===21,'exactly 21 structural assets');
const counts=assets.reduce((m,a)=>(m[a.kind]=(m[a.kind]||0)+1,m),{});
ok(counts.floor===9,'nine floors');
ok(counts.border===4,'four straight walls');
ok(counts.corner_outer===4,'four outer corners');
ok(counts.corner_inner===4,'four inner corners');
ok(new Set(assets.map(a=>a.id)).size===21,'unique stable IDs');
ok(new Set(assets.map(a=>`${a.atlas.col},${a.atlas.row}`)).size===21,'unique atlas slots');
ok(assets.every(a=>a.width===32&&a.height===32),'all assets 32x32');
ok(assets.every(a=>a.semantic===false),'all structural assets semantic:false');
ok(assets.filter(a=>a.kind==='floor').every(a=>a.rotationSafe===true),'floors rotation-safe');
ok(assets.filter(a=>a.kind!=='floor').every(a=>a.rotationSafe===false),'directional borders not rotation-safe');
ok(Object.keys(hashes).length===21,'hash registry has 21 assets');
ok(assets.every(a=>typeof hashes[a.file]==='string'&&hashes[a.file].length===64),'every asset has SHA-256');
ok(/7100\+i\*131/.test(generator)&&/9000\+idx/.test(generator),'generator uses fixed deterministic seeds');
ok(!/MAP_(DOOR|HERO|MONSTER|ITEM|NPC)/.test(JSON.stringify(manifest)),'batch contains no doors/actors/items');
ok(!/(moss|lava|water|blood|rune)/i.test(generator),'generator has no semantic environment motifs');
console.log(`RESULT ${pass} PASS / ${fail} FAIL`);
if(fail) process.exit(1);
